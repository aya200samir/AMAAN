    # ---- 5.9 Memory optimisation (downcasting) ----
    print("\n[9] Optimising data types (downcasting & categoricals)...")
    merged = optimise_dtypes(merged)
    print("   Memory optimisation completed.")

    print("\n" + "="*60)
    print("PoC COMPLETED SUCCESSFULLY")
    print("="*60)
    return merged

