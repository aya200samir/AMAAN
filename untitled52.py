def apply_sentiment_risk_penalty(predictions, sentiments, threshold=-0.5, penalty=5):
    """
    If sentiment < threshold, reduce prediction by penalty points.
    Ensures final score stays within [0, 100].
    """
    adjusted = predictions.copy()
    mask = sentiments < threshold
    adjusted[mask] = adjusted[mask] - penalty
    adjusted = np.clip(adjusted, 0, 100)
    return adjusted

