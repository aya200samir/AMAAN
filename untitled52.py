# 2. Synthetic one-to-one mapping (Olist customer ↔ PaySim nameOrig)
# ------------------------------------------------------------------
def create_synthetic_mapping(customers_df, paysim_df, random_state=42):
    """
    Creates a one-to-one mapping: each customer_unique_id gets a unique nameOrig.
    If sizes differ, the smaller set determines the number of mappings.
    Returns:
        - mapping_dict: {customer_id: assigned_nameOrig}
        - customers_mapped: customers_df with new column 'mapped_nameOrig'
    """
    np.random.seed(random_state)
    unique_customers = customers_df['customer_unique_id'].drop_duplicates().values
    unique_names = paysim_df['nameOrig'].drop_duplicates().values

    n = min(len(unique_customers), len(unique_names))
    selected_customers = np.random.choice(unique_customers, n, replace=False)
    selected_names = np.random.choice(unique_names, n, replace=False)

    mapping_dict = dict(zip(selected_customers, selected_names))

    # Apply mapping to a copy of customers (keep only mapped customers)
    customers_mapped = customers_df[customers_df['customer_unique_id'].isin(selected_customers)].copy()
    customers_mapped['mapped_nameOrig'] = customers_mapped['customer_unique_id'].map(mapping_dict)
    return mapping_dict, customers_mapped

# 3. Generate synthetic Target_Credit_Score (0-100)
# ------------------------------------------------------------------
def generate_target_credit_score(df):
    """
    Weighted logic:
    - Financial Health (PaySim): balance stability (low std of balance? we use transaction success rate)
      For simplicity: success = 1 if 'isFlaggedFraud' == 0 else 0. Also newbalanceOrig / oldbalanceOrg ratio.
    - Purchase Behaviour (Olist): order frequency (scaled to 0-1), total spend (scaled)
    - Risk indicators: high amount relative to oldbalance lowers score.
    """
    # Financial health component (0-40 points)
    # Assume 'isFlaggedFraud' exists (0 = success, 1 = fraud). If not, simulate.
    if 'isFlaggedFraud' not in df.columns:
        df['isFlaggedFraud'] = 0  # default no fraud
    success_flag = (df['isFlaggedFraud'] == 0).astype(int)
    # Balance ratio (newbalanceOrig / oldbalanceOrg) - careful with division by zero
    oldbal = df['oldbalanceOrg'].replace(0, np.nan)
    balance_ratio = df['newbalanceOrig'] / oldbal
    balance_ratio = balance_ratio.fillna(1.0).clip(0, 2)  # cap at 2 for healthy
    financial_health = (success_flag * 20) + (balance_ratio * 20).clip(0, 20)

    # Purchase behaviour component (0-40 points)
    # Frequency (count of orders per customer)
    freq = df.groupby('customer_unique_id')['customer_unique_id'].transform('count')
    freq_scaled = (freq - freq.min()) / (freq.max() - freq.min() + 1e-6)
    # Monetary: if 'payment_value' not present, simulate from amount
    if 'payment_value' not in df.columns:
        # use transaction amount as proxy
        monetary = df['amount'].fillna(df['amount'].median())
    else:
        monetary = df['payment_value']
    monetary_scaled = (monetary - monetary.min()) / (monetary.max() - monetary.min() + 1e-6)
    purchase_score = (freq_scaled * 20) + (monetary_scaled * 20)

    # Risk indicators (0-20 points, higher risk subtracts)
    # High amount relative to oldbalance
    amount_ratio = df['amount'] / (df['oldbalanceOrg'] + 1)
    high_risk = (amount_ratio > 0.5).astype(int) * 10  # lose 10 points if >50% of balance
    # Also if amount is very large (top 5%)
    high_amount = (df['amount'] > df['amount'].quantile(0.95)).astype(int) * 10
    risk_penalty = high_risk + high_amount

    raw_score = financial_health + purchase_score - risk_penalty
    # Clip to 0-100
    df['Target_Credit_Score'] = raw_score.clip(0, 100).astype(int)
    return df

# 4. RFM Metrics (Recency, Frequency, Monetary)
# ------------------------------------------------------------------
def compute_rfm_features(df, reference_date=None):
    """
    Requires: 'customer_unique_id', 'order_purchase_timestamp', and a monetary column
    (either 'payment_value' or 'amount' as proxy).
    """
    if reference_date is None:
        reference_date = df['order_purchase_timestamp'].max() + timedelta(days=1)

    # Monetary
    if 'payment_value' not in df.columns:
        df['payment_value'] = df['amount']  # use PaySim amount as proxy
    # Recency: days since last purchase
    df_rfm = df.groupby('customer_unique_id').agg({
        'order_purchase_timestamp': lambda x: (reference_date - x.max()).days,
        'order_purchase_timestamp': 'count',  # will be renamed
        'payment_value': 'sum'
    }).rename(columns={
        'order_purchase_timestamp': 'Recency_days',
        'order_purchase_timestamp': 'Frequency',
        'payment_value': 'Monetary'
    })
    # Fix duplicate column name issue
    df_rfm = df.groupby('customer_unique_id').agg(
        Recency_days=('order_purchase_timestamp', lambda x: (reference_date - x.max()).days),
        Frequency=('order_purchase_timestamp', 'count'),
        Monetary=('payment_value', 'sum')
    ).reset_index()
    # Merge back
    df = df.merge(df_rfm, on='customer_unique_id', how='left')
    return df

# 5. Financial ratios from PaySim
# ------------------------------------------------------------------
def compute_financial_ratios(df):
    """Add amount_to_balance_ratio and is_high_value_transaction indicator."""
    df['amount_to_balance_ratio'] = df['amount'] / (df['oldbalanceOrg'] + 1)
    # High value if amount > 75th percentile of global amount
    high_threshold = df['amount'].quantile(0.75)
    df['is_high_value_transaction'] = (df['amount'] > high_threshold).astype(int)
    return df

