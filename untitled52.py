# 1. Memory-safe random sampling (chunk-based)
# ------------------------------
def random_sample_csv(file_path, sample_size=100000, chunksize=10000, random_state=42):
    """
    Reads a large CSV and returns a random sample of ~sample_size rows.
    Iterates over chunks and samples proportionally without loading the whole file.
    """
    random.seed(random_state)
    np.random.seed(random_state)

    # Count total rows (excluding header)
    with open(file_path, 'r') as f:
        total_rows = sum(1 for _ in f) - 1

    frac = sample_size / total_rows if total_rows > sample_size else 1.0

    sampled_dfs = []
    for chunk in pd.read_csv(file_path, chunksize=chunksize):
        sampled_chunk = chunk.sample(frac=frac, random_state=random_state)
        sampled_dfs.append(sampled_chunk)

        current_size = sum(len(df) for df in sampled_dfs)
        if current_size >= sample_size * 1.1:
            break

    result = pd.concat(sampled_dfs, ignore_index=True)
    if len(result) > sample_size:
        result = result.sample(n=sample_size, random_state=random_state)
    return result

# 2. Per‑group outlier detection & imputation
# ------------------------------
def detect_outliers_iqr(series):
    """Return boolean mask where True indicates outlier."""
    Q1 = series.quantile(0.25)
    Q3 = series.quantile(0.75)
    IQR = Q3 - Q1
    lower = Q1 - 1.5 * IQR
    upper = Q3 + 1.5 * IQR
    return (series < lower) | (series > upper)

def impute_numeric_column_per_group(df, col, group_col=None):
    """
    Impute missing values in a numeric column.
    - If outliers exist WITHIN EACH GROUP → use group median.
    - Else → use group mean.
    If group_col is None, applies globally.
    """
    if group_col is None or group_col not in df.columns:
        # Global imputation (fallback)
        non_null = df[col].dropna()
        if len(non_null) == 0:
            return df
        outliers_exist = detect_outliers_iqr(non_null).any()
        fill_value = non_null.median() if outliers_exist else non_null.mean()
        df[col].fillna(fill_value, inplace=True)
        return df

    # Per‑group imputation
    for group_val, group_data in df.groupby(group_col):
        mask = df[group_col] == group_val
        non_null = group_data[col].dropna()
        if len(non_null) == 0:
            continue
        outliers_exist = detect_outliers_iqr(non_null).any()
        fill_value = non_null.median() if outliers_exist else non_null.mean()
        df.loc[mask & df[col].isnull(), col] = fill_value
    return df

def impute_categorical_column(df, col):
    """Impute missing values with the mode (global)."""
    mode_val = df[col].mode()
    if not mode_val.empty:
        df[col].fillna(mode_val[0], inplace=True)
    return df

# 3. Memory optimisation (downcasting + categoricals)
# ------------------------------
def optimise_dtypes(df):
    """
    - Downcast int64 → int32 / float64 → float32 where safe.
    - Convert low‑cardinality object columns (unique < 50) to 'category'.
    """
    for col in df.columns:
        col_type = df[col].dtype

        if col_type == 'int64':
            df[col] = pd.to_numeric(df[col], downcast='integer')
        elif col_type == 'float64':
            df[col] = pd.to_numeric(df[col], downcast='float')
        elif col_type == 'object':
            if df[col].nunique() / len(df) < 0.5 and df[col].nunique() < 50:
                df[col] = df[col].astype('category')
    return df


