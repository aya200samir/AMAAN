# ------------------------------
# 5. Local Interpretability - Function for Individual Customer
# ------------------------------
def explain_customer_decision(customer_index, X_scaled, shap_values_all=None, feature_names=None, model=None, scaler=None):
    """
    Generate a waterfall plot and a human-readable explanation for a single customer.

    Parameters:
    - customer_index: row index in X_test_scaled (or any scaled array)
    - X_scaled: the full scaled test array (numpy)
    - shap_values_all: precomputed SHAP values for the entire test set (optional, will compute if None)
    - feature_names: list of feature names
    - model: trained Keras model (needed if computing SHAP on the fly)
    - scaler: fitted StandardScaler (for inverse transforming values to original scale)

    Returns:
    - A waterfall plot displayed inline
    - A printed plain‑English summary
    """
    if shap_values_all is None:
        # Compute SHAP values for this single sample (expensive, but works)
        sample = X_scaled[customer_index:customer_index+1]
        shap_val = explainer.shap_values(sample)
        if isinstance(shap_val, list):
            shap_val = shap_val[0]
        shap_val = np.array(shap_val).flatten() # Ensure it's 1D
    else:
        # shap_values_all is expected to be (num_samples, num_features, 1) or (num_samples, num_features)
        # Extract the specific customer's SHAP values
        shap_val = shap_values_all[customer_index]
        shap_val = np.array(shap_val).flatten() # Ensure it's 1D

    # Process base_values to ensure it's a scalar or numpy array, not a TF tensor
    base_value = explainer.expected_value
    if isinstance(base_value, tf.Tensor):
        base_value = base_value.numpy()
    if isinstance(base_value, list):
        base_value = base_value[0]

    # Waterfall plot
    plt.figure(figsize=(12, 6))
    shap.waterfall_plot(
        shap.Explanation(
            values=shap_val, # shap_val is now guaranteed to be 1D
            base_values=base_value,
            data=X_scaled[customer_index],
            feature_names=feature_names
        ),
        show=False
    )
    plt.title(f"SHAP Waterfall Plot for Customer {customer_index}", fontsize=14)
    plt.tight_layout()
    plt.show()

    # Human-readable explanation
    # Get original (unscaled) feature values if scaler provided
    if scaler:
        original_values = scaler.inverse_transform(X_scaled[customer_index:customer_index+1])[0]
    else:
        original_values = X_scaled[customer_index]

    # Compute contribution direction
    contributions = []
    for i, name in enumerate(feature_names):
        shap_contrib = shap_val[i] # shap_val is already 1D
        if abs(shap_contrib) > 0.05:  # only show non‑trivial contributions
            direction = "increased" if shap_contrib > 0 else "decreased"
            contributions.append(f"{name}: {shap_contrib:+.2f} points")

    # Sort by absolute magnitude
    contributions_sorted = sorted(contributions, key=lambda x: abs(float(x.split(':')[1].split()[0])), reverse=True)
    # Build message
    pred_score = model.predict(X_scaled[customer_index:customer_index+1])[0][0]
    top_positive = [c for c in contributions_sorted if '+' in c][:2]
    top_negative = [c for c in contributions_sorted if '-' in c][:2]

    explanation = f"Customer {customer_index} received a predicted credit score of {pred_score:.1f}.\n"
    if top_positive:
        explanation += f"  Positive contributors: {', '.join(top_positive)}.\n"
    if top_negative:
        explanation += f"  Negative contributors: {', '.join(top_negative)}.\n"
    if not contributions_sorted:
        explanation += "  All features had negligible impact (near baseline)."

    print("\n" + "="*70)
    print("🔍 LOCAL EXPLANATION (Human‑Readable)")
    print("="*70)
    print(explanation)
    print("="*70)

    return shap_val

