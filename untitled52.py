def map_step_to_time_features(df, step_col='step'):
    """Map PaySim 'step' (hourly units) into time_of_day and day_of_week."""
    hour = df[step_col] % 24
    day_idx = (df[step_col] // 24) % 7  # 0 = Monday

    conditions = [
        (hour >= 5) & (hour < 12),
        (hour >= 12) & (hour < 17),
        (hour >= 17) & (hour < 21),
        (hour >= 21) | (hour < 5)
    ]
    choices = ['Morning', 'Afternoon', 'Evening', 'Night']
    df['time_of_day'] = np.select(conditions, choices, default='')

    days = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday']
    df['day_of_week'] = day_idx.map(lambda x: days[int(x)])
    return df

