    merged['order_hour'] = merged['order_purchase_timestamp'].dt.hour
    merged['order_dayofweek'] = merged['order_purchase_timestamp'].dt.dayofweek

    # PaySim step → time features
    if 'step' in merged.columns:
        merged = map_step_to_time_features(merged, step_col='step')
        print("   Added 'time_of_day' and 'day_of_week' from PaySim 'step'.")

